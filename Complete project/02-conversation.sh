#!/bin/bash
#-----------------------------------------------------------
#Shell Script 02 - Simple Conversation Using echo
# Script Name : conversation.sh
# Purpose     : Display a simple conversation between
#               Ramesh and Suresh using the echo command.
# Author      : Mahesh
#-----------------------------------------------------------

# Print the first line of the conversation.
# The echo command displays the text exactly as written.
echo "Ramesh: hi Suresh, how are you?"

# Print the second line of the conversation.
echo "Suresh: hi Ramesh, I am fine, how are you?"

# Print the third line of the conversation.
echo "Ramesh: I am fine, Thanks for asking, what else?"

# Print the fourth line of the conversation.
echo "Suresh: Nothing new, Just going on"